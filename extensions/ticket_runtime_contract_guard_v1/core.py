"""Trusted request contract, tool-call gate, and evidence-based answer renderer.

This module does not load a model or execute real tools. It wraps the frozen
controller v1.1 against its in-memory backend without changing that controller.
The contract must be supplied by trusted application code, never model text.
"""

from __future__ import annotations

import copy
from dataclasses import dataclass
import json
import re
from typing import Any

from extensions.ticket_runtime_controller_v1_1 import core as controller
from extensions.ticket_runtime_controller_v1_1_design import core as design


TOOL_BLOCK = re.compile(r"<tool_call>\s*(.*?)\s*</tool_call>", re.DOTALL)
FIELDS = {"ticket_id", "status", "version", "priority", "assignee_id"}
STATUSES = {"open", "in_progress", "resolved", "closed"}
PRIORITIES = {"low", "normal", "high"}
TOOL_ARGS = {
    "get_ticket": {"ticket_id"},
    "update_ticket_status": {"ticket_id", "status", "expected_version"},
}


def _object(pairs: list[tuple[str, Any]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate_json_key")
        result[key] = value
    return result


def parse_model_output(text: str) -> tuple[str, Any]:
    """Accept only a plain final draft or complete, strict tool-call blocks."""
    if not isinstance(text, str) or not text.strip() or len(text) > 16384:
        raise ValueError("empty_or_oversize_output")
    text = text.strip()
    matches = list(TOOL_BLOCK.finditer(text))
    if not matches:
        if "<tool_call" in text or "</tool_call" in text:
            raise ValueError("malformed_tool_block")
        return "final", text
    if TOOL_BLOCK.sub("", text).strip() or len(matches) > 4:
        raise ValueError("mixed_or_excessive_tool_output")
    calls = []
    for match in matches:
        call = json.loads(match.group(1), object_pairs_hook=_object,
                          parse_constant=lambda _: (_ for _ in ()).throw(ValueError("nonfinite_json")))
        if not isinstance(call, dict) or set(call) != {"name", "arguments"}:
            raise ValueError("invalid_call_shape")
        calls.append(call)
    return "calls", calls


def validate_call(call: dict) -> str | None:
    """Schema validation is fail-closed and runs before backend preview."""
    if not isinstance(call, dict) or set(call) != {"name", "arguments"}:
        return "invalid_call_shape"
    name, args = call["name"], call["arguments"]
    if name not in TOOL_ARGS or not isinstance(args, dict) or set(args) != TOOL_ARGS[name]:
        return "invalid_tool_or_arguments"
    for key, value in args.items():
        if key == "expected_version":
            if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                return "invalid_expected_version"
        elif not isinstance(value, str) or not value or len(value) > (2000 if key == "description" else 120):
            return "invalid_string_argument"
    if "status" in args and args["status"] not in STATUSES:
        return "invalid_status"
    if "priority" in args and args["priority"] not in PRIORITIES:
        return "invalid_priority"
    return None


@dataclass(frozen=True)
class TrustedContract:
    """Fields and goal are trusted orchestration data, not generated by the model."""

    target_ticket_id: str
    required_fields: tuple[str, ...]
    profile: str = "json"
    target_status: str | None = None
    locale: str = "en"

    def __post_init__(self) -> None:
        if not isinstance(self.target_ticket_id, str) or not self.target_ticket_id or not self.required_fields or "ticket_id" not in self.required_fields:
            raise ValueError("incomplete_trusted_contract")
        if len(set(self.required_fields)) != len(self.required_fields) or not set(self.required_fields) <= FIELDS:
            raise ValueError("unsupported_or_duplicate_answer_field")
        if self.profile not in {"json", "sentence", "explicit_actions"} or self.locale not in {"en", "zh"}:
            raise ValueError("unsupported_answer_profile")
        if self.target_status is not None and self.target_status not in STATUSES:
            raise ValueError("unsupported_target_status")
        if self.target_status is not None and "status" not in self.required_fields:
            raise ValueError("status_goal_requires_status_answer")


class GuardedSession:
    """One stateful CPU episode; no direct access to real ticket services."""

    def __init__(self, *, contract: TrustedContract, scope: dict,
                 backend: controller.SimulatedTicketBackend,
                 trusted_write_allowed: bool) -> None:
        if scope.get("target_ticket_ids") != [contract.target_ticket_id]:
            raise ValueError("contract_scope_target_mismatch")
        if not isinstance(trusted_write_allowed, bool):
            raise ValueError("trusted_write_permission_must_be_boolean")
        if not set(scope.get("allowed_tools", [])) <= set(TOOL_ARGS):
            raise ValueError("unsupported_tool_in_scope")
        if contract.target_status is None and "update_ticket_status" in scope.get("allowed_tools", []):
            raise ValueError("status_write_requires_trusted_goal")
        if contract.target_status is not None and "update_ticket_status" not in scope.get("allowed_tools", []):
            raise ValueError("goal_tool_missing_from_scope")
        self.contract = contract
        self.controller = controller.ControllerSession(
            scope=copy.deepcopy(scope), trusted_write_allowed=trusted_write_allowed, backend=backend)
        self.audit: list[dict] = []
        self.rejections: dict[str, int] = {}
        self.halted = False

    def _reject(self, reason: str, call: dict | None = None, *,
                backend_executed: bool = False, response: dict | None = None) -> dict:
        state = self.controller.observed.get(self.contract.target_ticket_id)
        key = json.dumps([reason, call, state], sort_keys=True, ensure_ascii=False, default=str)
        self.rejections[key] = self.rejections.get(key, 0) + 1
        if self.rejections[key] >= 2:
            self.halted = True
        result = {"allowed": False, "reason": reason, "halted": self.halted,
                  "backend_executed": backend_executed, "response": copy.deepcopy(response)}
        self.audit.append({"call": copy.deepcopy(call), **result})
        return result

    def _goal_reason(self, call: dict) -> str | None:
        if call["name"] != "update_ticket_status" or self.contract.target_status is None:
            return None
        target = call["arguments"]["status"]
        observed = self.controller.observed.get(self.contract.target_ticket_id)
        if observed is None:
            return "read_before_status_write"
        current = observed.get("status")
        if current == self.contract.target_status:
            return "goal_already_satisfied"
        next_state = design.ALLOWED_NEXT.get(current)
        walk = next_state
        remaining = set()
        while walk is not None and walk not in remaining:
            remaining.add(walk)
            if walk == self.contract.target_status:
                break
            walk = design.ALLOWED_NEXT.get(walk)
        if self.contract.target_status not in remaining:
            return "goal_not_reachable_from_observed_state"
        if target != next_state:
            return "write_not_next_step_to_goal"
        return None

    def propose(self, call: dict) -> dict:
        if self.halted:
            return self._reject("episode_halted", call)
        invalid = validate_call(call)
        if invalid:
            return self._reject(invalid, call)
        if "ticket_id" in call["arguments"] and call["arguments"]["ticket_id"] != self.contract.target_ticket_id:
            return self._reject("target_outside_trusted_contract", call)
        goal_error = self._goal_reason(call)
        if goal_error:
            return self._reject(goal_error, call)
        before_preview = len(self.controller.backend.preview_invocations)
        decision, response = self.controller.propose(copy.deepcopy(call))
        reached = len(self.controller.backend.preview_invocations) > before_preview
        if not decision["allowed"]:
            return self._reject("controller_blocked:" + ",".join(decision["reasons"]), call,
                                backend_executed=reached, response=response)
        if response is None or not response.get("ok"):
            error = (response or {}).get("error", {}).get("code", "missing_backend_response")
            return self._reject("backend_error:" + error, call,
                                backend_executed=reached, response=response)
        self.rejections.clear()
        result = {"allowed": True, "decision": copy.deepcopy(decision),
                  "response": copy.deepcopy(response), "backend_executed": reached,
                  "halted": self.halted}
        self.audit.append({"call": copy.deepcopy(call), **result})
        return result

    def dispatch(self, text: str) -> dict:
        """Execute parsed calls one at a time; a later call sees all earlier state."""
        if self.halted:
            return self._reject("episode_halted")
        try:
            kind, value = parse_model_output(text)
        except (ValueError, TypeError, json.JSONDecodeError) as exc:
            return self._reject("invalid_model_output:" + str(exc))
        if kind == "final":
            # A model draft is never trusted as a statement of ticket state.
            answer = self.render()
            return {"kind": "final", "model_draft_discarded": True, **answer}
        results = []
        for call in value:
            result = self.propose(call)
            results.append(result)
            if self.halted:
                break
        return {"kind": "calls", "results": results, "halted": self.halted}

    def render(self) -> dict:
        """Render only verified state; never copy fields from a model draft."""
        state = self.controller.observed.get(self.contract.target_ticket_id)
        committed = self.controller.backend.tickets.get(self.contract.target_ticket_id)
        if state is None or state != committed:
            return {"allowed": False, "reason": "no_current_verified_state"}
        fields = {}
        for field in self.contract.required_fields:
            if field not in state:
                return {"allowed": False, "reason": "missing_verified_field:" + field}
            fields[field] = state[field]
        complete = self.contract.target_status is None or state.get("status") == self.contract.target_status
        if self.contract.profile == "json":
            # The requested JSON field set stays exact. Goal outcome is separate
            # trusted metadata, not an unrequested key in the user's object.
            text = json.dumps(fields, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
        else:
            labels = {"ticket_id": "工单ID" if self.contract.locale == "zh" else "ticket_id",
                      "status": "状态" if self.contract.locale == "zh" else "status",
                      "version": "版本" if self.contract.locale == "zh" else "version",
                      "priority": "优先级" if self.contract.locale == "zh" else "priority",
                      "assignee_id": "负责人规范ID" if self.contract.locale == "zh" else "assignee_id"}
            values = [f"{labels[key]}={('未分配' if self.contract.locale == 'zh' else 'unassigned') if value is None else value}"
                      for key, value in fields.items()]
            text = ("；" if self.contract.locale == "zh" else "; ").join(values) + ("。" if self.contract.locale == "zh" else ".")
            if self.contract.profile == "explicit_actions":
                writes = sum(1 for item in self.audit if item.get("allowed") and
                             item.get("call", {}).get("name") == "update_ticket_status")
                text = ((f"已执行状态写入 {writes} 次；核实结果：" if self.contract.locale == "zh" else
                         f"Executed {writes} status writes; verified result: ") + text)
            if self.contract.target_status is not None:
                text += ((" 已达到请求目标。" if complete else " 未达到请求目标；不得宣称完成。") if self.contract.locale == "zh"
                         else (" Requested goal completed." if complete else " Requested goal not completed."))
        return {"allowed": True, "text": text, "verified_fields": fields,
                "operation_completed": complete, "source": "committed_and_observed_state"}
